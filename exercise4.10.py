pizzas = ["pepperoni", "cheese", "mushroom",
          "bbq chicken", "tuna", "beef", "hawaiian"]

print("The first three items in the list are:")
print(pizzas[:3])

print("\nThree items from the middle of the list are:")
print(pizzas[2:5])

print("\nThe last three items in the list are:")
print(pizzas[-3:])